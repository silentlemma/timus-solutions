fn main() {
    let mut s = String::new();
    io::stdin().read_to_string(&mut s).unwrap();
    let v: Vec<usize> = s
        .split_ascii_whitespace()
        .map(|x| x.parse().unwrap())
        .collect();
    let (n, m) = match v[..] {
        [n, m] => (n, m),
        _ => return,
    };
    let (small, large) = (n.min(m), n.max(m));
    let cells = PATTERNS
        .iter()
        .find(|p| p.0 == small && p.1 == large)
        .unwrap()
        .2
        .as_bytes();
    let mut out = String::new();
    let mut ones = 0;
    for r in 0..n {
        for c in 0..m {
            // a tall board uses the pattern turned on its side
            let cell = if n <= m {
                cells[r * m + c]
            } else {
                cells[c * n + r]
            };
            out.push(cell as char);
            if cell == b'1' {
                ones += 1;
            }
        }
        out.push('\n');
    }
    print!("{}\n{}", ones / 2, out);
}
