import java.util.*;

public class Main {
    // cells covered by a smallest set of tiles that leaves exactly one way to
    // finish each board with n <= m, row by row; printed by 1609_constructive_table.py
    static final Object[][] PATTERNS = {
        {1, 2, "00"},
        {1, 4, "0000"},
        {1, 6, "000000"},
        {1, 8, "00000000"},
        {1, 10, "0000000000"},
        {2, 2, "1100"},
        {2, 3, "110000"},
        {2, 4, "01100000"},
        {2, 5, "1111000000"},
        {2, 6, "110110000000"},
        {2, 7, "01101100000000"},
        {2, 8, "1111011000000000"},
        {2, 9, "110110110000000000"},
        {2, 10, "01101101100000000000"},
        {3, 4, "011000000000"},
        {3, 6, "100000100000000110"},
        {3, 8, "011000000000000000000110"},
        {3, 10, "100000011010000000000001100000"},
        {4, 4, "1100011000000000"},
        {4, 5, "11000011000000000000"},
        {4, 6, "011000001100000000000000"},
        {4, 7, "1100000011110000000000000000"},
        {4, 8, "01100000001111000000000000000000"},
        {4, 9, "110001100011000110000000000000000000"},
        {4, 10, "1100011000011000110000000000000000000000"},
        {5, 6, "011000001100000000000000000000"},
        {5, 8, "0110000000111100000000000000000000000000"},
        {5, 10, "10000000001100000000010000000000000011000000011000"},
        {6, 6, "110000011000001100000000000000000000"},
        {6, 7, "110000001100000011000000000000000000000000"},
        {6, 8, "011000000011000000011000000000000000000000000000"},
        {6, 9, "110000000011000000001111000000000000000000000000000000"},
        {6, 10, "011000000000110000000001111000000000000000000000000000000000"},
        {7, 8, "01100000001100000001100000000000000000000000000000000000"},
        {7, 10, "0110000000001100000000011110000000000000000000000000000000000000000000"},
        {8, 8, "1100000001100000001100000001100000000000000000000000000000000000"},
        {8, 9, "110000000011000000001100000000110000000000000000000000000000000000000000"},
        {8, 10,
         "011000000000110000000001100000000011000000000000000000000000000000000000"
             + "00000000"},
        {9, 10,
         "011000000000110000000001100000000011000000000000000000000000000000000000"
             + "000000000000000000"},
        {10, 10,
         "110000000001100000000011000000000110000000001100000000000000000000000000"
             + "0000000000000000000000000000"},
    };

    public static void main(String[] args) {
        Scanner in = new Scanner(System.in);
        if (!in.hasNextInt())
            return;
        int n = in.nextInt(), m = in.nextInt();
        int small = Math.min(n, m), large = Math.max(n, m);
        String cells = null;
        for (Object[] p : PATTERNS)
            if ((Integer)p[0] == small && (Integer)p[1] == large)
                cells = (String)p[2];
        StringBuilder out = new StringBuilder();
        int ones = 0;
        for (int r = 0; r < n; r++) {
            for (int c = 0; c < m; c++) {
                // a tall board uses the pattern turned on its side
                char cell = n <= m ? cells.charAt(r * m + c) : cells.charAt(c * n + r);
                out.append(cell);
                if (cell == '1')
                    ones++;
            }
            out.append('\n');
        }
        System.out.print((ones / 2) + "\n" + out);
    }
}
