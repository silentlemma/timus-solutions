#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <sstream>
#include <string>
#include <vector>

// the longest walks from 1, found offline by an exhaustive search with
// pruning; each entry "n: walk" serves every count of inns from n up to
// the next entry, since the walk only grows where a longer one appears
const char *WALKS =
    "2: 1 2 "
    "4: 1 2 4 "
    "6: 1 3 6 2 4 "
    "8: 1 3 6 2 4 8 "
    "9: 1 9 3 6 2 4 8 "
    "12: 1 5 10 2 8 4 12 6 3 9 "
    "15: 1 7 14 2 8 4 12 6 3 15 5 10 "
    "16: 1 7 14 2 10 5 15 3 6 12 4 8 16 "
    "18: 1 7 14 2 10 5 15 3 9 18 6 12 4 8 16 "
    "20: 1 7 14 2 8 16 4 12 6 18 9 3 15 5 10 20 "
    "21: 1 9 18 6 12 3 15 5 10 20 4 8 16 2 14 7 21 "
    "24: 1 11 22 2 14 7 21 3 9 18 6 12 24 8 16 4 20 10 5 15 "
    "27: 1 11 22 2 14 7 21 3 15 5 10 20 4 16 8 24 12 6 18 9 27 "
    "28: 1 11 22 2 10 20 5 15 3 21 7 14 28 4 16 8 24 12 6 18 9 27 "
    "30: 1 11 22 2 14 28 7 21 3 27 9 18 6 12 24 8 16 4 20 10 30 15 5 25 "
    "32: 1 11 22 2 14 28 7 21 3 27 9 18 6 12 24 8 16 32 4 20 10 30 15 5 25 "
    "33: 1 25 5 15 30 10 20 4 16 32 8 24 12 6 18 9 27 3 21 7 14 28 2 22 11 33 "
    "35: 1 13 26 2 22 11 33 3 27 9 18 6 12 24 8 16 32 4 20 10 30 15 5 35 7 14 "
    "28 "
    "36: 1 13 26 2 22 11 33 3 27 9 18 36 6 12 24 8 16 32 4 20 10 30 15 5 35 7 "
    "14 28 "
    "39: 1 22 11 33 3 27 9 18 36 6 12 24 8 16 32 4 20 10 30 15 5 35 7 14 28 2 "
    "26 13 39 "
    "40: 1 25 5 35 7 14 28 4 16 32 8 40 20 10 30 6 24 12 36 18 9 27 3 33 11 "
    "22 2 26 13 39 "
    "42: 1 25 5 35 7 21 42 14 28 4 16 32 8 40 20 10 30 6 24 12 36 18 9 27 3 "
    "33 11 22 2 26 13 39 "
    "44: 1 17 34 2 26 13 39 3 27 9 18 36 12 24 6 42 14 28 7 35 5 15 30 10 20 "
    "40 8 16 32 4 44 22 11 33 "
    "45: 1 17 34 2 26 13 39 3 27 9 18 36 12 24 6 42 14 28 7 35 5 45 15 30 10 "
    "20 40 8 16 32 4 44 22 11 33 "
    "48: 1 17 34 2 26 13 39 3 27 9 18 36 12 6 24 48 16 32 8 40 20 10 30 15 45 "
    "5 35 7 21 42 14 28 4 44 22 11 33 "
    "50: 1 17 34 2 26 13 39 3 27 9 45 15 30 6 18 36 12 24 48 16 32 8 40 20 10 "
    "50 25 5 35 7 21 42 14 28 4 44 22 11 33 ";

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;
    std::istringstream words(WALKS);
    std::vector<std::string> best;
    std::string word;
    while (words >> word) {
        if (word.back() == ':') {
            if (atoi(word.c_str()) > n) break;
            best.clear();
        } else {
            best.push_back(word);
        }
    }
    printf("%d\n", (int)best.size());
    for (size_t i = 0; i < best.size(); i++) {
        printf(i ? " %s" : "%s", best[i].c_str());
    }
    printf("\n");
    return 0;
}
