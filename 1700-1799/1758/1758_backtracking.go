func main() {
	var n int
	if _, err := fmt.Scan(&n); err != nil {
		return
	}
	var best []string
	for _, word := range strings.Fields(walks) {
		if strings.HasSuffix(word, ":") {
			limit, _ := strconv.Atoi(strings.TrimSuffix(word, ":"))
			if limit > n {
				break
			}
			best = best[:0]
		} else {
			best = append(best, word)
		}
	}
	fmt.Println(len(best))
	fmt.Println(strings.Join(best, " "))
}
